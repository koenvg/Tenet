import { expect, test } from '../playwright-fixture.js';
import { seedNavigation, navigationPath } from './navigation-fixture.js';
import { sessionKey } from '../../../src/recording/archive.js';
import { reveal } from '../ui-navigation.js';

for (const width of [1380, 1103, 390]) test(`rule-first navigation retains exact mounted state and history without group requests at ${width}px`, async ({ withInspector }) => {
  await withInspector('navigation', async ({ page, app }) => {
    await page.setViewportSize({ width, height: 1000 });
    const groupRequests: string[] = [];
    page.on('request', request => { if (request.url().endsWith('/groups')) groupRequests.push(request.url()); });
    await page.locator('.decision-summary').waitFor();
    expect(await page.locator('.repeated-uncertainty, .uncertainty-group, .inspection-switch, #finding-category, .pane-resizer').count()).toBe(0);
    expect(await page.locator('.rule-main-footer > p[role=status]').textContent()).toContain('Partial archive');
    await reveal(page, '.why-disclosure'); await reveal(page, '.recorded-disclosure'); await reveal(page, '.exact-rules');
    const exact = page.locator('.exact-rule-data');
    await exact.evaluate(el => { el.dataset.retained = 'mounted'; el.scrollTop = 20; });
    await page.locator('.story-title h2').focus();
    const exactScroll = await exact.evaluate(el => el.scrollTop), link = page.url();
    await page.waitForResponse(response => response.url().includes('/rules?'));
    expect(await exact.getAttribute('data-retained')).toBe('mounted');
    expect(await exact.evaluate(el => el.scrollTop)).toBe(exactScroll);
    expect(await page.locator('.story-title h2').evaluate(el => document.activeElement === el)).toBe(true);
    expect(await page.locator('.recorded-disclosure').getAttribute('open')).not.toBeNull();
    expect(page.url()).toBe(link);
    const session = new URL(link).searchParams.get('session');
    const filtered = await (await page.request.get(`/api/sessions/${session}?category=violation`)).json();
    expect(filtered.invocations).toHaveLength(0);
    const calls = await (await page.request.get(`/api/sessions/${session}`)).json();
    expect(calls.invocations).toHaveLength(4);
    const next = calls.invocations.find((row: { actionPreview: { value: string } }) => row.actionPreview.value === 'src/billing/format.ts');
    expect(next.id).toMatch(/^[a-f0-9]{64}$/);
    await page.evaluate(([session, id]) => { history.pushState(null, '', `/?session=${session}&invocation=${id}`); dispatchEvent(new PopStateEvent('popstate')); }, [session, next.id]);
    await expect.poll(() => page.locator('.story-action').textContent()).toBe('src/billing/format.ts');
    const selected = page.url(); expect(selected).not.toContain('format.ts');
    await page.goBack(); await page.locator('.decision-summary').waitFor();
    await expect.poll(() => page.url()).toBe(link);
    await page.goForward(); await expect.poll(() => page.url()).toBe(selected);
    await page.getByRole('button', { name: 'Close', exact: true }).click();
    const issues = page.locator('.recording-issues'), toggle = issues.locator(':scope > summary');
    await toggle.focus(); await page.keyboard.press('Enter');
    expect(await page.locator('.issues-body').textContent()).toContain('A rebuild alone does not update a running reader.');
    await issues.evaluate(el => el.dataset.retained = 'mounted');
    await page.waitForResponse(response => response.url().includes('/api/sessions?'));
    expect(await issues.getAttribute('data-retained')).toBe('mounted');
    expect(await issues.getAttribute('open')).not.toBeNull();
    expect(await toggle.evaluate(el => document.activeElement === el)).toBe(true);
    await page.getByRole('button', { name: 'Refresh archive' }).click();
    await expect.poll(() => page.getByRole('button', { name: 'Refresh archive' }).isEnabled()).toBe(true);
    expect(groupRequests).toEqual([]);
    expect(await page.evaluate(() => performance.getEntriesByType('resource').some(entry => new URL(entry.name).pathname.endsWith('/groups')))).toBe(false);
    const data = await (await fetch(`${app.origin}/api/sessions/${session}/groups`)).json();
    expect(data.groups.items.map((group: { count: number }) => group.count).sort()).toEqual([1, 3]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }, { base: false, seed: directory => seedNavigation(directory, true), path: navigationPath + `&invocation=${sessionKey('call-0')}` });
});
